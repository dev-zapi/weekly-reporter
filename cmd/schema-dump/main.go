// schema-dump 把 drizzle 迁移语料合并成 sqlc 的 schema 输入。
//
// 为什么需要它：sqlc 的 SQLite 解析器吃不下 drizzle 的迁移语料（反引号标识符、
// ALTER TABLE、DML、PRAGMA 混在同一份文件里），也吃不下按 journal 顺序拼起来的
// 迁移串——只有「最终态建表语句」才能解析。所以由本脚本把 41 条迁移按 journal
// 顺序真实应用到空库，再从 sqlite_master 导出最终 schema。
//
// 产物 internal/db/schema.sql 签入仓库、由本脚本重生成，绝不手改（ADR-0025）。
package main

import (
	"database/sql"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	_ "modernc.org/sqlite"
)

const breakpoint = "--> statement-breakpoint"

// journal 只取排序所需的字段；迁移顺序的唯一权威是 entries 的先后，
// 不是文件名序（0012 的两个迁移字典序与语义序相反）。
type journal struct {
	Entries []journalEntry `json:"entries"`
}

type journalEntry struct {
	Tag string `json:"tag"`
}

func main() {
	root := flag.String("root", ".", "仓库根目录")
	out := flag.String("out", "internal/db/schema.sql", "输出文件（相对 root）")
	flag.Parse()

	entries, err := readJournal(filepath.Join(*root, "drizzle", "meta", "_journal.json"))
	if err != nil {
		fatal(err)
	}

	schema, err := dumpSchema(filepath.Join(*root, "drizzle"), entries)
	if err != nil {
		fatal(err)
	}

	outPath := filepath.Join(*root, *out)
	if err := os.WriteFile(outPath, []byte(schema), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d migrations, %d bytes)\n", outPath, len(entries), len(schema))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "schema-dump:", err)
	os.Exit(1)
}

func readJournal(path string) ([]journalEntry, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var j journal
	if err := json.Unmarshal(raw, &j); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	if len(j.Entries) == 0 {
		return nil, fmt.Errorf("%s has no entries", path)
	}
	return j.Entries, nil
}

// dumpSchema 在内存库里回放全部迁移，再导出建表/建索引语句。
func dumpSchema(migrationsDir string, entries []journalEntry) (string, error) {
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		return "", err
	}
	defer db.Close()

	for _, entry := range entries {
		path := filepath.Join(migrationsDir, entry.Tag+".sql")
		raw, err := os.ReadFile(path)
		if err != nil {
			return "", fmt.Errorf("read migration %s: %w", entry.Tag, err)
		}
		// 按 breakpoint 切分而不是按 ';'：迁移正文里字符串/JSON 字面量可能含分号。
		for _, stmt := range strings.Split(string(raw), breakpoint) {
			stmt = strings.TrimSpace(stmt)
			if stmt == "" {
				continue
			}
			if _, err := db.Exec(stmt); err != nil {
				return "", fmt.Errorf("apply %s: %w\n%s", entry.Tag, err, stmt)
			}
		}
	}

	rows, err := db.Query(`
		SELECT type, name, sql FROM sqlite_master
		WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
		ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name`)
	if err != nil {
		return "", err
	}
	defer rows.Close()

	type object struct{ kind, name, ddl string }
	var objects []object
	for rows.Next() {
		var o object
		if err := rows.Scan(&o.kind, &o.name, &o.ddl); err != nil {
			return "", err
		}
		// 账本是迁移簿记，不是业务 schema，喂给 sqlc 只会多出一张表。
		if o.name == "__drizzle_migrations" {
			continue
		}
		objects = append(objects, o)
	}
	if err := rows.Err(); err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("-- Code generated by cmd/schema-dump. DO NOT EDIT.\n")
	b.WriteString("-- 来源：drizzle/ 41 条迁移按 meta/_journal.json 顺序应用到空库后的最终态。\n")
	b.WriteString("-- sqlc 只能解析最终态建表语句；语料新增迁移后跑 make schema 重生成。\n\n")
	for _, o := range objects {
		// 反引号标识符是 sqlc 的已知解析坑（sqlc#3800）：表名有时能认，列名一律当字面量。
		// 归一化成双引号是必需步骤，不是美化。
		b.WriteString(strings.ReplaceAll(o.ddl, "`", "\"") + ";\n\n")
	}
	return b.String(), nil
}
